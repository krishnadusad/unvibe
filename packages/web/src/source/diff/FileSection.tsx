/**
 * One file in the diff pane (PRD §4.13): file header + hunk list.
 *
 * Behaviour ported from `prototype.html` (class names kept so
 * `styles/prototype.css` applies unchanged):
 * - header: collapse chevron, dir (middle-shortened, #227) + file name
 *   (truncates with an ellipsis), +/− counts, reviewed count,
 *   mark-file-reviewed checkbox (indeterminate while partial) — the
 *   counts and checkbox stay fixed at the header's right edge;
 * - hunks render through hidden-run grouping; hunk cards (the agent
 *   summary) exist independently of folding; folding only hides code;
 * - the hunk header's fold chevron is the single unfold control (issue
 *   #162): a folded hunk shows no extra placeholder row;
 * - each hunk is its own section (header, card, code
 *   table), so the hunk header's vertical stick reaches `#right` past every
 *   horizontal scroller (#140); unified code tables scroll sideways per
 *   hunk, split rows pair del/add runs in two equal halves; in-table slot
 *   rows stay pinned to the pane width via `.pin`.
 *
 * Performance: the file header always renders (cheap); the hunk table
 * renders lazily on first intersection with the pane, so a 300-file diff
 * mounts ~300 headers instead of 5k hunks. `eager` bypasses the lazy gate
 * (above-the-fold files, file jumps, `revealSource` targets).
 */
